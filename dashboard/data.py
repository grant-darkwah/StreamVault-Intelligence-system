class DashboardDataError(Exception):
    """Raised when dashboard data is missing or invalid."""


@st.cache_data(show_spinner="Loading StreamVault datasets...")
def load_dashboard_data(output_dir: str = "out") -> dict:
    """Load and validate the analytical datasets generated by the pipeline."""

    directory = Path(output_dir)
    datasets = {}

    for name, (filename, file_type) in FILES.items():
        path = directory / filename

        if not path.is_file():
            raise DashboardDataError(
                f"Missing required dataset: {path}. Run python3 run_pipeline.py first."
            )

        try:
            if file_type == "parquet":
                datasets[name] = pd.read_parquet(path)
            else:
                datasets[name] = pd.read_csv(path)
        except Exception as error:
            raise DashboardDataError(f"Could not read {path}: {error}") from error

        missing_columns = REQUIRED_COLUMNS[name] - set(datasets[name].columns)

        if missing_columns:
            raise DashboardDataError(
                f"{filename} is missing required columns: "
                f"{', '.join(sorted(missing_columns))}"
            )

    return datasets


def get_data_summary(datasets: dict) -> dict:
    """Return accurate candidate reconciliation and dataset KPIs."""

    reconciliation = datasets["reconciliation"]

    valid_rows = reconciliation.loc[reconciliation["is_valid"].eq(True)]

    unique_valid_ids = valid_rows["tmdb_id"].nunique()

    duplicate_excess = (
        valid_rows.loc[valid_rows["is_duplicate"].eq(True)]["tmdb_id"]
        .duplicated()
        .sum()
    )

    return {
        "candidate_records": len(reconciliation),
        "invalid_records": int(reconciliation["is_valid"].eq(False).sum()),
        "valid_candidate_rows": len(valid_rows),
        "unique_valid_ids": unique_valid_ids,
        "duplicate_excess": int(duplicate_excess),
        "analysed_titles": len(datasets["films"]),
        "unretrieved_valid_ids": unique_valid_ids - len(datasets["films"]),
        "franchise_collections": len(datasets["franchise_all"]),
        "standalone_titles": len(datasets["standalone_all"]),
    }
